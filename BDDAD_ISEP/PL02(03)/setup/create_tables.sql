CREATE TABLE PL02_TEACHER (
   CITIZEN_CARD     VARCHAR2(20)
      CONSTRAINT PK_TEACHER PRIMARY KEY,
   ACRONYM          VARCHAR2(10) NOT NULL,
   NAME             VARCHAR2(150) NOT NULL,
   DATE_OF_BIRTH    DATE NOT NULL,
   CURRENT_CATEGORY VARCHAR2(100) NOT NULL,
   CURRENT_AREA     VARCHAR2(100) NOT NULL
);

CREATE TABLE PL02_DEPARTMENT (
   DEPT_NUMBER  NUMBER(10)
      CONSTRAINT PK_DEPARTMENT PRIMARY KEY,
   ACRONYM      VARCHAR2(10) NOT NULL,
   ROOM         VARCHAR2(50) NOT NULL,
   PRESIDENT_CC VARCHAR2(20) NOT NULL,
   CONSTRAINT FK_DEPARTMENT_PRESIDENT FOREIGN KEY ( PRESIDENT_CC )
      REFERENCES PL02_TEACHER ( CITIZEN_CARD ),
   CONSTRAINT UK_DEPARTMENT_PRESIDENT UNIQUE ( PRESIDENT_CC )
);

CREATE TABLE PL02_STUDENT (
   CITIZEN_CARD   VARCHAR2(20)
      CONSTRAINT PK_STUDENT PRIMARY KEY,
   STUDENT_NUMBER NUMBER(10) NOT NULL,
   DATE_OF_BIRTH  DATE NOT NULL,
   DEGREE         VARCHAR2(100) NOT NULL,
   DEPT_NUMBER    NUMBER(10) NOT NULL,
   ADVISOR_CC     VARCHAR2(20),
   CONSTRAINT UK_STUDENT_NUMBER UNIQUE ( STUDENT_NUMBER ),
   CONSTRAINT FK_STUDENT_DEPARTMENT FOREIGN KEY ( DEPT_NUMBER )
      REFERENCES PL02_DEPARTMENT ( DEPT_NUMBER ),
   CONSTRAINT FK_STUDENT_ADVISOR FOREIGN KEY ( ADVISOR_CC )
      REFERENCES PL02_STUDENT ( CITIZEN_CARD )
);

CREATE TABLE PL02_PROJECT (
   PROJECT_NUMBER NUMBER(10)
      CONSTRAINT PK_PROJECT PRIMARY KEY,
   ACRONYM        VARCHAR2(10) NOT NULL,
   DESCRIPTION    VARCHAR2(500) NOT NULL,
   FUNDING_ENTITY VARCHAR2(100) NOT NULL,
   START_DATE     DATE NOT NULL,
   END_DATE       DATE NOT NULL,
   BUDGET         NUMBER(12,2) NOT NULL,
   MANAGER_CC     VARCHAR2(20) NOT NULL,
   CONSTRAINT FK_PROJECT_MANAGER FOREIGN KEY ( MANAGER_CC )
      REFERENCES PL02_TEACHER ( CITIZEN_CARD )
);

CREATE TABLE PL02_TEACHER_PROJECT (
   TEACHER_CC     VARCHAR2(20),
   PROJECT_NUMBER NUMBER(10),
   CONSTRAINT PK_TEACHER_PROJECT PRIMARY KEY ( TEACHER_CC,
                                               PROJECT_NUMBER ),
   CONSTRAINT FK_TP_TEACHER FOREIGN KEY ( TEACHER_CC )
      REFERENCES PL02_TEACHER ( CITIZEN_CARD ),
   CONSTRAINT FK_TP_PROJECT FOREIGN KEY ( PROJECT_NUMBER )
      REFERENCES PL02_PROJECT ( PROJECT_NUMBER )
);

CREATE TABLE PL02_STUDENT_PROJECT (
   STUDENT_CC     VARCHAR2(20),
   PROJECT_NUMBER NUMBER(10),
   MENTOR_CC      VARCHAR2(20) NOT NULL,
   CONSTRAINT PK_STUDENT_PROJECT PRIMARY KEY ( STUDENT_CC,
                                               PROJECT_NUMBER ),
   CONSTRAINT FK_SP_STUDENT FOREIGN KEY ( STUDENT_CC )
      REFERENCES PL02_STUDENT ( CITIZEN_CARD ),
   CONSTRAINT FK_SP_PROJECT FOREIGN KEY ( PROJECT_NUMBER )
      REFERENCES PL02_PROJECT ( PROJECT_NUMBER ),
   CONSTRAINT FK_SP_MENTOR FOREIGN KEY ( MENTOR_CC )
      REFERENCES PL02_TEACHER ( CITIZEN_CARD )
);

CREATE TABLE PL02_TEACHER_DEPARTMENT (
   TEACHER_CC         VARCHAR2(20),
   DEPT_NUMBER        NUMBER(10),
   PERCENTAGE_OF_TIME NUMBER(5,2) NOT NULL,
   CONSTRAINT PK_TEACHER_DEPARTMENT PRIMARY KEY ( TEACHER_CC,
                                                  DEPT_NUMBER ),
   CONSTRAINT FK_TD_TEACHER FOREIGN KEY ( TEACHER_CC )
      REFERENCES PL02_TEACHER ( CITIZEN_CARD ),
   CONSTRAINT FK_TD_DEPARTMENT FOREIGN KEY ( DEPT_NUMBER )
      REFERENCES PL02_DEPARTMENT ( DEPT_NUMBER ),
   CONSTRAINT CK_TD_PERCENTAGE
      CHECK ( PERCENTAGE_OF_TIME > 0
         AND PERCENTAGE_OF_TIME <= 100 )
);