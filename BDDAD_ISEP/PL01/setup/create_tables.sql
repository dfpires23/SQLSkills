CREATE TABLE PL01_ADDRESS (
   ID          NUMBER(10)
      CONSTRAINT PK_ADDRESS PRIMARY KEY,
   STREET      VARCHAR2(200) NOT NULL,
   CITY        VARCHAR2(100) NOT NULL,
   POSTAL_CODE VARCHAR2(20) NOT NULL,
   COUNTRY     VARCHAR2(100) NOT NULL
);

CREATE TABLE PL01_INSTRUMENT (
   ID   NUMBER(10)
      CONSTRAINT PK_INSTRUMENT PRIMARY KEY,
   NAME VARCHAR2(100) NOT NULL,
   TYPE VARCHAR2(100) NOT NULL
);

CREATE TABLE PL01_MUSICIAN (
   ID         NUMBER(10)
      CONSTRAINT PK_MUSICIAN PRIMARY KEY,
   NAME       VARCHAR2(150) NOT NULL,
   ADDRESS_ID NUMBER(10),
   CONSTRAINT FK_MUSICIAN_ADDRESS FOREIGN KEY ( ADDRESS_ID )
      REFERENCES PL01_ADDRESS ( ID )
);

CREATE TABLE PL01_ALBUM (
   CODE           VARCHAR2(50)
      CONSTRAINT PK_ALBUM PRIMARY KEY,
   TITLE          VARCHAR2(200) NOT NULL,
   RECORDING_DATE DATE NOT NULL,
   FORMAT         VARCHAR2(50) NOT NULL,
   RELEASE_DATE   DATE,
   PRODUCER_ID    NUMBER(10) NOT NULL,
   CONSTRAINT FK_ALBUM_PRODUCER FOREIGN KEY ( PRODUCER_ID )
      REFERENCES PL01_MUSICIAN ( ID )
);

CREATE TABLE PL01_SONG (
   ID         NUMBER(10)
      CONSTRAINT PK_SONG PRIMARY KEY,
   TITLE      VARCHAR2(200) NOT NULL,
   DURATION   INTERVAL DAY TO SECOND NOT NULL,
   ALBUM_CODE VARCHAR2(50) NOT NULL,
   CONSTRAINT FK_SONG_ALBUM FOREIGN KEY ( ALBUM_CODE )
      REFERENCES PL01_ALBUM ( CODE )
);

CREATE TABLE PL01_MUSICIAN_INSTRUMENT (
   MUSICIAN_ID   NUMBER(10),
   INSTRUMENT_ID NUMBER(10),
   SINCE_DATE    DATE NOT NULL,
   CONSTRAINT PK_MUSICIAN_INSTRUMENT PRIMARY KEY ( MUSICIAN_ID,
                                                   INSTRUMENT_ID ),
   CONSTRAINT FK_MI_MUSICIAN FOREIGN KEY ( MUSICIAN_ID )
      REFERENCES PL01_MUSICIAN ( ID ),
   CONSTRAINT FK_MI_INSTRUMENT FOREIGN KEY ( INSTRUMENT_ID )
      REFERENCES PL01_INSTRUMENT ( ID )
);

CREATE TABLE PL01_MUSICIAN_SONG (
   MUSICIAN_ID NUMBER(10),
   SONG_ID     NUMBER(10),
   CONSTRAINT PK_MUSICIAN_SONG PRIMARY KEY ( MUSICIAN_ID,
                                             SONG_ID ),
   CONSTRAINT FK_MS_MUSICIAN FOREIGN KEY ( MUSICIAN_ID )
      REFERENCES PL01_MUSICIAN ( ID ),
   CONSTRAINT FK_MS_SONG FOREIGN KEY ( SONG_ID )
      REFERENCES PL01_SONG ( ID )
);