SET SERVEROUTPUT ON;

--happy
DECLARE
   VRESULT NUMBER;
BEGIN
   VRESULT := PKG_CUSTOMER_ORDER.ADDCUSTOMERORDER(
      PCUSTOMERID   => 1,
      PDELIVERYTIME => SYSTIMESTAMP + 1
   );

   IF VRESULT > 0 THEN
      DBMS_OUTPUT.PUT_LINE('Costumer order created successfully!');
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   END IF;

END;
/

--unhappy
DECLARE
   VRESULT NUMBER;
BEGIN
   VRESULT := PKG_CUSTOMER_ORDER.ADDCUSTOMERORDER(
      PCUSTOMERID   => 1,
      PDELIVERYTIME => SYSTIMESTAMP - 1
   );

   IF VRESULT > 0 THEN
      DBMS_OUTPUT.PUT_LINE('Costumer order created successfully!');
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   END IF;

END;
/

