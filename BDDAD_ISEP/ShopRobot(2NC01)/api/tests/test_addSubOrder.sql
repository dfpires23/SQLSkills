SET SERVEROUTPUT ON;

-- happy
DECLARE
   VRESULT     NUMBER;
   VORDERID    SUBORDER.ORDERID%TYPE;
   VSUBORDERNO SUBORDER.SUBORDERNO%TYPE;
   VROBOTID    ROBOT.ROBOTID%TYPE;
BEGIN
   SELECT ORDERID
     INTO VORDERID
     FROM CUSTOMERORDER
    WHERE ROWNUM = 1;

   SELECT ROBOTID
     INTO VROBOTID
     FROM ROBOT
    WHERE STATUS = 'READY'
      AND ROWNUM = 1;

   SELECT NVL(
      MAX(SUBORDERNO),
      0
   ) + 1
     INTO VSUBORDERNO
     FROM SUBORDER
    WHERE ORDERID = VORDERID;

   VRESULT := PKG_CUSTOMER_ORDER.ADDSUBORDER(
      PORDERID    => VORDERID,
      PSUBORDERNO => VSUBORDERNO,
      PROBOTID    => VROBOTID
   );

   IF VRESULT > 0 THEN
      DBMS_OUTPUT.PUT_LINE('Sub-order created successfully!');
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   END IF;

END;
