-- happy
DECLARE
   VRESULT NUMBER;
BEGIN
   VRESULT := PKG_AREA.ADDAREAPOLYGON(
      PAREAID     => 10006,
      PPOLYGONNO  => 1,
      PBOUNDARYNO => 1,
      PPOINTORDER => 1,
      PLONGITUDE  => - 8.6291,
      PLATITUDE   => 41.1579
   );

   IF VRESULT > 0 THEN
      DBMS_OUTPUT.PUT_LINE('Area Polygon created successfully!');
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   END IF;

END;

