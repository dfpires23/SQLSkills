SET SERVEROUTPUT ON;

-- happy
DECLARE
   VRESULT NUMBER;
BEGIN
   VRESULT := PKG_ROBOT.ADDROBOTTYPE(
      PMAXWEIGHTKG => 999,
      PMAXVOLUMEL  => 999,
      PHASCOOLING  => 0
   );

   IF VRESULT > 0 THEN
      DBMS_OUTPUT.PUT_LINE('Robot type created successfully!');
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   END IF;

END;
