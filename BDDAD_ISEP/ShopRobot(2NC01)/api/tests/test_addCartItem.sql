--HAPPY
DECLARE
   VRESULT NUMBER;
BEGIN
   VRESULT := ADDCARTITEM(
      PCARTID    => 1,
      PPRODUCTID => 1,
      PQUANTITY  => 1
   );

   IF VRESULT > 0 THEN
      DBMS_OUTPUT.PUT_LINE('Product created successfully!');
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   END IF;

END;

