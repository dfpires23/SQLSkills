DECLARE
   VRESULT NUMBER;
BEGIN
   VRESULT := PKG_SHOPPING.ADDSHOPLEVEL(
      PSHOPPINGID => 2,
      PLEVELVALUE => 0
   );
   IF VRESULT > 0 THEN
      DBMS_OUTPUT.PUT_LINE('Shopping Level created successfully!');
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: ' || VRESULT);
   END IF;

END;

