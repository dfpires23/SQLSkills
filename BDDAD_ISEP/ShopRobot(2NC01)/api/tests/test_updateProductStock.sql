-- happy
DECLARE
   VRESULT    BOOLEAN;
   VPRODUCTID PRODUCT.PRODUCTID%TYPE;
BEGIN
   SELECT PRODUCTID
     INTO VPRODUCTID
     FROM PRODUCT
    WHERE STOCKUNITS >= 1
      AND ROWNUM = 1;

   VRESULT := PKG_CUSTOMER_ORDER.UPDATEPRODUCTSTOCK(
      PPRODUCTID => VPRODUCTID,
      PQUANTITY  => 1
   );
   IF VRESULT THEN
      DBMS_OUTPUT.PUT_LINE('Product stock updated successfully!');
   ELSE
      DBMS_OUTPUT.PUT_LINE('Result: FALSE');
   END IF;

END;

