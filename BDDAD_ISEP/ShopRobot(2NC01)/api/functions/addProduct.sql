CREATE OR REPLACE FUNCTION ADDPRODUCT (
   PSTOREID      IN PRODUCT.STOREID%TYPE,
   PNAME         IN PRODUCT.NAME%TYPE,
   PWEIGHTKG     IN PRODUCT.WEIGHTKG%TYPE,
   PVOLUMEL      IN PRODUCT.VOLUMEL%TYPE,
   PNEEDSCOOLING IN PRODUCT.NEEDSCOOLING%TYPE,
   PPRICEEUR     IN PRODUCT.PRICEEUR%TYPE,
   PSTOCKUNITS   IN PRODUCT.STOCKUNITS%TYPE
) RETURN NUMBER IS

   PCODE           PRODUCT.CODE%TYPE;
   PPRODUCTID      PRODUCT.PRODUCTID%TYPE;
   T_STORE_ID      NUMBER(1);
   T_PRODUCT_STORE NUMBER(1);
   CURSOR GET_STORE_ID (
      PSTOREID IN STORE.STOREID%TYPE
   ) IS
   SELECT 1
     FROM STORE
    WHERE STOREID = PSTOREID;

   CURSOR GET_PRODUCT_STORE (
      PCODE    IN PRODUCT.CODE%TYPE,
      PSTOREID IN PRODUCT.STOREID%TYPE
   ) IS
   SELECT 1
     FROM PRODUCT
    WHERE PCODE = CODE
      AND STOREID = PSTOREID;

BEGIN
   IF PSTOREID IS NULL
   OR PNAME IS NULL
   OR PWEIGHTKG IS NULL
   OR PVOLUMEL IS NULL
   OR PNEEDSCOOLING IS NULL
   OR PPRICEEUR IS NULL
   OR PSTOCKUNITS IS NULL THEN
      RAISE_APPLICATION_ERROR(
         -20000,
         'All parameters are required.'
      );
   END IF;

   OPEN GET_STORE_ID(PSTOREID);
   FETCH GET_STORE_ID INTO T_STORE_ID;
   IF GET_STORE_ID%NOTFOUND THEN
      CLOSE GET_STORE_ID;
      RAISE_APPLICATION_ERROR(
         -20600,
         'Store not found!'
      );
   END IF;

   CLOSE GET_STORE_ID;
   OPEN GET_PRODUCT_STORE(
      PCODE,
      PSTOREID
   );
   FETCH GET_PRODUCT_STORE INTO T_PRODUCT_STORE;
   IF GET_PRODUCT_STORE%FOUND THEN
      CLOSE GET_PRODUCT_STORE;
      RAISE_APPLICATION_ERROR(
         -20601,
         'Product code already exists for the store!'
      );
   END IF;

   CLOSE GET_PRODUCT_STORE;
   LOCK TABLE PRODUCT IN EXCLUSIVE MODE;
   SELECT NVL(
      MAX(PRODUCTID),
      0
   ) + 1
     INTO PPRODUCTID
     FROM PRODUCT;

   PCODE := 'P'
            || LPAD(
      PPRODUCTID,
      6,
      '0'
   );
   INSERT INTO PRODUCT (
      PRODUCTID,
      CODE,
      STOREID,
      NAME,
      WEIGHTKG,
      VOLUMEL,
      NEEDSCOOLING,
      PRICEEUR,
      STOCKUNITS
   ) VALUES
      ( PPRODUCTID,
        PCODE,
        PSTOREID,
        PNAME,
        PWEIGHTKG,
        PVOLUMEL,
        PNEEDSCOOLING,
        PPRICEEUR,
        PSTOCKUNITS );

   COMMIT;
   RETURN PPRODUCTID;
EXCEPTION
   WHEN OTHERS THEN
      IF GET_STORE_ID%ISOPEN THEN
         CLOSE GET_STORE_ID;
      END IF;
      IF GET_PRODUCT_STORE%ISOPEN THEN
         CLOSE GET_PRODUCT_STORE;
      END IF;
      RAISE;
END;