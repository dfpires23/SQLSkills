CREATE OR REPLACE FUNCTION ADDSTORE (
   PSTOREID IN STORE.STOREID%TYPE,
   PAREAID  IN STORE.AREAID%TYPE
) RETURN NUMBER IS

   T_STORE_AREA NUMBER;
   T_STORE_ID   NUMBER;
   CURSOR GET_STORE_AREA (
      PAREAID IN STORE.AREAID%TYPE
   ) IS
   SELECT 1
     FROM AREACLASSIFICATION
    WHERE CLASSIFICATIONTYPE = 'shop'
      AND AREAID = PAREAID;

   CURSOR GET_STORE_ID (
      PSTOREID IN STORE.STOREID%TYPE
   ) IS
   SELECT 1
     FROM STORE
    WHERE STOREID = PSTOREID;

BEGIN
   IF PSTOREID IS NULL
   OR PAREAID IS NULL THEN
      RAISE_APPLICATION_ERROR(
         -20000,
         'All parameters are required.'
      );
   END IF;

   OPEN GET_STORE_AREA(PAREAID);
   FETCH GET_STORE_AREA INTO T_STORE_AREA;
   IF GET_STORE_AREA%NOTFOUND THEN
      CLOSE GET_STORE_AREA;
      RAISE_APPLICATION_ERROR(
         -20700,
         'Wrong area classification'
      );
      RETURN 0;
   END IF;

   CLOSE GET_STORE_AREA;
   OPEN GET_STORE_ID(PSTOREID);
   FETCH GET_STORE_ID INTO T_STORE_ID;
   IF GET_STORE_ID%FOUND THEN
      CLOSE GET_STORE_ID;
      RAISE_APPLICATION_ERROR(
         -20701,
         'Store already exists'
      );
      RETURN 0;
   END IF;

   CLOSE GET_STORE_ID;
   INSERT INTO STORE (
      STOREID,
      AREAID
   ) VALUES
      ( PSTOREID,
        PAREAID );

   COMMIT;
   RETURN 1;
EXCEPTION
   WHEN OTHERS THEN
      IF GET_STORE_AREA%ISOPEN THEN
         CLOSE GET_STORE_AREA;
      END IF;
      IF GET_STORE_ID%ISOPEN THEN
         CLOSE GET_STORE_ID;
      END IF;
      RAISE;
END;