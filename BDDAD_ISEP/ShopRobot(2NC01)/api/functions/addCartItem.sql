CREATE OR REPLACE FUNCTION ADDCARTITEM (
   PCARTID    IN CARTITEM.CARTID%TYPE,
   PPRODUCTID IN CARTITEM.PRODUCTID%TYPE,
   PQUANTITY  IN CARTITEM.QUANTITY%TYPE
) RETURN NUMBER IS

   T_CART_ID      NUMBER(1);
   T_CART_PRODUCT NUMBER(1);
   T_PRODUCT      NUMBER(10);
   T_QTY          NUMBER(19);
   CURSOR GET_CART_ID (
      PCARTID IN CARTITEM.CARTID%TYPE
   ) IS
   SELECT 1
     FROM SHOPPINGCART
    WHERE CARTID = PCARTID;

   CURSOR GET_PRODUCT_QTY (
      PPRODUCTID IN CARTITEM.PRODUCTID%TYPE,
      PQUANTITY  IN CARTITEM.QUANTITY%TYPE
   ) IS
   SELECT PRODUCTID,
          STOCKUNITS
     FROM PRODUCT
    WHERE PRODUCTID = PPRODUCTID;

   CURSOR GET_CART_PRODUCT (
      PCARTID IN CARTITEM.CARTID%TYPE
   ) IS
   SELECT 1
     FROM CARTITEM
    WHERE CARTID = PCARTID
      AND PRODUCTID = PPRODUCTID;

BEGIN
   IF PCARTID IS NULL
   OR PPRODUCTID IS NULL
   OR PQUANTITY IS NULL THEN
      RAISE_APPLICATION_ERROR(
         -20000,
         'All parameters are required.'
      );
   END IF;

   IF PQUANTITY <= 0 THEN
      RAISE_APPLICATION_ERROR(
         -20400,
         'Qunatity must be above 0.'
      );
   END IF;
   OPEN GET_CART_PRODUCT(PCARTID);
   FETCH GET_CART_PRODUCT INTO T_CART_PRODUCT;
   IF GET_CART_PRODUCT%FOUND THEN
      CLOSE GET_CART_PRODUCT;
      RAISE_APPLICATION_ERROR(
         -20401,
         'Produtc already exists on cart'
      );
   END IF;

   CLOSE GET_CART_PRODUCT;
   OPEN GET_PRODUCT_QTY(
      PPRODUCTID,
      PQUANTITY
   );
   FETCH GET_PRODUCT_QTY INTO
      T_PRODUCT,
      T_QTY;
   IF GET_PRODUCT_QTY%NOTFOUND THEN
      CLOSE GET_PRODUCT_QTY;
      RAISE_APPLICATION_ERROR(
         -20402,
         'Product not found'
      );
   ELSIF T_QTY < PQUANTITY THEN
      CLOSE GET_PRODUCT_QTY;
      RAISE_APPLICATION_ERROR(
         -20403,
         'Cart quantity exceeds stock'
      );
   END IF;

   CLOSE GET_PRODUCT_QTY;
   OPEN GET_CART_ID(PCARTID);
   FETCH GET_CART_ID INTO T_CART_ID;
   IF GET_CART_ID%NOTFOUND THEN
      CLOSE GET_CART_ID;
      RAISE_APPLICATION_ERROR(
         -20404,
         'Shopping cart not found'
      );
   END IF;

   CLOSE GET_CART_ID;
   INSERT INTO CARTITEM (
      CARTID,
      PRODUCTID,
      QUANTITY
   ) VALUES
      ( PCARTID,
        PPRODUCTID,
        PQUANTITY );

   COMMIT;
   RETURN 1;
EXCEPTION
   WHEN OTHERS THEN
      IF GET_CART_PRODUCT%ISOPEN THEN
         CLOSE GET_CART_PRODUCT;
      END IF;
      IF GET_PRODUCT_QTY%ISOPEN THEN
         CLOSE GET_PRODUCT_QTY;
      END IF;
      IF GET_CART_ID%ISOPEN THEN
         CLOSE GET_CART_ID;
      END IF;
      RAISE;
END;