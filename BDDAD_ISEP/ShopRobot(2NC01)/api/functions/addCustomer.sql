CREATE OR REPLACE FUNCTION ADDCUSTOMER (
   PEMAIL     IN CUSTOMER.EMAIL%TYPE,
   PFIRSTNAME IN CUSTOMER.FIRSTNAME%TYPE,
   PLASTNAME  IN CUSTOMER.LASTNAME%TYPE
) RETURN NUMBER IS

   PCARTID          SHOPPINGCART.CARTID%TYPE;
   PCUSTOMERID      CUSTOMER.CUSTOMERID%TYPE;
   T_CUSTOMER_EMAIL NUMBER(1);
   CURSOR GET_CUSTOMER_EMAIL (
      PEMAIL IN CUSTOMER.EMAIL%TYPE
   ) IS
   SELECT 1
     FROM CUSTOMER
    WHERE EMAIL = PEMAIL;

BEGIN
   IF PEMAIL IS NULL
   OR PFIRSTNAME IS NULL
   OR PLASTNAME IS NULL THEN
      RAISE_APPLICATION_ERROR(
         -20000,
         'All parameters are required.'
      );
   END IF;

   OPEN GET_CUSTOMER_EMAIL(PEMAIL);
   FETCH GET_CUSTOMER_EMAIL INTO T_CUSTOMER_EMAIL;
   IF GET_CUSTOMER_EMAIL%FOUND THEN
      CLOSE GET_CUSTOMER_EMAIL;
      RAISE_APPLICATION_ERROR(
         -20500,
         'Email already exists'
      );
   END IF;

   CLOSE GET_CUSTOMER_EMAIL;
   BEGIN
      SAVEPOINT SP_ADD_CUSTOMER;
      LOCK TABLE CUSTOMER IN EXCLUSIVE MODE;
      LOCK TABLE SHOPPINGCART IN EXCLUSIVE MODE;
      SELECT NVL(
         MAX(CUSTOMERID),
         0
      ) + 1
        INTO PCUSTOMERID
        FROM CUSTOMER;

      SELECT NVL(
         MAX(CARTID),
         0
      ) + 1
        INTO PCARTID
        FROM SHOPPINGCART;

      INSERT INTO CUSTOMER (
         CUSTOMERID,
         EMAIL,
         FIRSTNAME,
         LASTNAME
      ) VALUES
         ( PCUSTOMERID,
           PEMAIL,
           PFIRSTNAME,
           PLASTNAME );

      INSERT INTO SHOPPINGCART (
         CARTID,
         CUSTOMERID
      ) VALUES
         ( PCARTID,
           PCUSTOMERID );

      COMMIT;
      RETURN PCUSTOMERID;
   EXCEPTION
      WHEN OTHERS THEN
         IF GET_CUSTOMER_EMAIL%ISOPEN THEN
            CLOSE GET_CUSTOMER_EMAIL;
         END IF;
         ROLLBACK TO SP_ADD_CUSTOMER;
         RAISE;
   END;

END;