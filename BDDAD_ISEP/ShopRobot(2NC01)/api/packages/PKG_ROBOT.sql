CREATE OR REPLACE PACKAGE PKG_ROBOT AS
   FUNCTION ADDROBOT (
      PSHOPPINGID  IN ROBOT.SHOPPINGID%TYPE,
      PNAME        IN ROBOT.NAME%TYPE,
      PROBOTTYPEID IN ROBOT.TYPEID%TYPE,
      PBATTERYPCT  IN ROBOT.BATTERYPCT%TYPE,
      PSTATUS      IN ROBOT.STATUS%TYPE
   ) RETURN NUMBER;

   FUNCTION ADDROBOTTYPE (
      PMAXWEIGHTKG IN ROBOTTYPE.MAXWEIGHTKG%TYPE,
      PMAXVOLUMEL  IN ROBOTTYPE.MAXVOLUMEL%TYPE,
      PHASCOOLING  IN ROBOTTYPE.HASCOOLING%TYPE
   ) RETURN NUMBER;

END PKG_ROBOT;
/

CREATE OR REPLACE PACKAGE BODY PKG_ROBOT AS

   CURSOR GET_ROBOT_TYPE_ID (
      PROBOTTYPEID IN ROBOT.TYPEID%TYPE
   ) IS
   SELECT 1
     FROM ROBOTTYPE
    WHERE ID = PROBOTTYPEID;
	
/*	CURSOR GET_ROBOT_CODE(pRobotCode IN robot.robotCode%TYPE) IS
	SELECT 1 FROM robot WHERE robotCode = pRobotCode;*/
   CURSOR GET_ROBOT_TYPE (
      PMAXWEIGHTKG IN ROBOTTYPE.MAXWEIGHTKG%TYPE,
      PMAXVOLUMEL  IN ROBOTTYPE.MAXVOLUMEL%TYPE,
      PHASCOOLING  IN ROBOTTYPE.HASCOOLING%TYPE
   ) IS
   SELECT 1
     FROM ROBOTTYPE
    WHERE MAXWEIGHTKG = PMAXWEIGHTKG
      AND MAXVOLUMEL = PMAXVOLUMEL
      AND HASCOOLING = PHASCOOLING;

   CURSOR GET_SHOP (
      PSHOPPINGID IN SHOPPING.SHOPPINGID%TYPE
   ) IS
   SELECT 1
     FROM SHOPPING
    WHERE SHOPPINGID = PSHOPPINGID;

   FUNCTION ADDROBOT (
      PSHOPPINGID  IN ROBOT.SHOPPINGID%TYPE,
      PNAME        IN ROBOT.NAME%TYPE,
      PROBOTTYPEID IN ROBOT.TYPEID%TYPE,
      PBATTERYPCT  IN ROBOT.BATTERYPCT%TYPE,
      PSTATUS      IN ROBOT.STATUS%TYPE
   ) RETURN NUMBER IS

      T_ROBOT_TYPE_ID NUMBER;
      T_ROBOT_CODE    NUMBER;
      T_SHOP          NUMBER;
      PROBOTID        ROBOT.ROBOTID%TYPE;
      PROBOTCODE      ROBOT.ROBOTCODE%TYPE;
   BEGIN
      IF PSHOPPINGID IS NULL
      OR PNAME IS NULL
      OR PROBOTTYPEID IS NULL
      OR PBATTERYPCT IS NULL
      OR PSTATUS IS NULL THEN
         RAISE_APPLICATION_ERROR(
            -20000,
            'All parameters are required.'
         );
      END IF;

      IF PBATTERYPCT NOT BETWEEN 0 AND 100 THEN
         RAISE_APPLICATION_ERROR(
            -20100,
            'Battery percentage invalid'
         );
      END IF;

      IF PSTATUS NOT IN ( 'READY',
                          'BUSY',
                          'CHARGING',
                          'MAINTENANCE' ) THEN
         RAISE_APPLICATION_ERROR(
            -20101,
            'Robot status invalid'
         );
      END IF;

      OPEN GET_ROBOT_TYPE_ID(PROBOTTYPEID);
      FETCH GET_ROBOT_TYPE_ID INTO T_ROBOT_TYPE_ID;
      IF GET_ROBOT_TYPE_ID%NOTFOUND THEN
         CLOSE GET_ROBOT_TYPE_ID;
         RAISE_APPLICATION_ERROR(
            -20102,
            'Robot Type not found!'
         );
      END IF;

      CLOSE GET_ROBOT_TYPE_ID;
		
/*		OPEN GET_ROBOT_CODE(pRobotCode);
		FETCH GET_ROBOT_CODE INTO T_ROBOT_CODE;	
			IF GET_ROBOT_CODE%FOUND THEN
				CLOSE GET_ROBOT_CODE;
				RAISE_APPLICATION_ERROR(-20103,'Robot Code already exists!');
			END IF;	
		CLOSE GET_ROBOT_CODE;*/
      OPEN GET_SHOP(PSHOPPINGID);
      FETCH GET_SHOP INTO T_SHOP;
      IF GET_SHOP%NOTFOUND THEN
         CLOSE GET_SHOP;
         RAISE_APPLICATION_ERROR(
            -20202,
            'Shopping Id not found'
         );
         RETURN 0;
      END IF;

      CLOSE GET_SHOP;
      LOCK TABLE ROBOT IN EXCLUSIVE MODE;
      SELECT NVL(
         MAX(ROBOTID),
         0
      ) + 1
        INTO PROBOTID
        FROM ROBOT;

      PROBOTCODE := 'Robot'
                    || LPAD(
         PROBOTID,
         4,
         '0'
      );
      INSERT INTO ROBOT (
         SHOPPINGID,
         ROBOTID,
         ROBOTCODE,
         NAME,
         TYPEID,
         BATTERYPCT,
         STATUS
      ) VALUES
         ( PSHOPPINGID,
           PROBOTID,
           PROBOTCODE,
           PNAME,
           PROBOTTYPEID,
           PBATTERYPCT,
           PSTATUS );

      COMMIT;
      RETURN PROBOTID;
   EXCEPTION
      WHEN OTHERS THEN
         IF GET_ROBOT_TYPE_ID%ISOPEN THEN
            CLOSE GET_ROBOT_TYPE_ID;
         END IF;
/*	    	IF GET_ROBOT_CODE%ISOPEN THEN
	            CLOSE GET_ROBOT_CODE;
	        END IF;*/
         IF GET_SHOP%ISOPEN THEN
            CLOSE GET_SHOP;
         END IF;
         RAISE;
   END ADDROBOT;

   FUNCTION ADDROBOTTYPE (
      PMAXWEIGHTKG IN ROBOTTYPE.MAXWEIGHTKG%TYPE,
      PMAXVOLUMEL  IN ROBOTTYPE.MAXVOLUMEL%TYPE,
      PHASCOOLING  IN ROBOTTYPE.HASCOOLING%TYPE
   ) RETURN NUMBER IS
      T_ROBOT_TYPE NUMBER(1);
      PID          ROBOTTYPE.ID%TYPE;
   BEGIN
      IF PMAXWEIGHTKG IS NULL
      OR PMAXVOLUMEL IS NULL
      OR PHASCOOLING IS NULL THEN
         RAISE_APPLICATION_ERROR(
            -20000,
            'All parameters are required.'
         );
      END IF;

      OPEN GET_ROBOT_TYPE(
         PMAXWEIGHTKG,
         PMAXVOLUMEL,
         PHASCOOLING
      );
      FETCH GET_ROBOT_TYPE INTO T_ROBOT_TYPE;
      IF GET_ROBOT_TYPE%FOUND THEN
         CLOSE GET_ROBOT_TYPE;
         RAISE_APPLICATION_ERROR(
            -20103,
            'Robot Type already exists!'
         );
      END IF;

      CLOSE GET_ROBOT_TYPE;
      LOCK TABLE ROBOTTYPE IN EXCLUSIVE MODE;
      SELECT NVL(
         MAX(ID),
         0
      ) + 1
        INTO PID
        FROM ROBOTTYPE;

      INSERT INTO ROBOTTYPE (
         ID,
         MAXWEIGHTKG,
         MAXVOLUMEL,
         HASCOOLING
      ) VALUES
         ( PID,
           PMAXWEIGHTKG,
           PMAXVOLUMEL,
           PHASCOOLING );

      COMMIT;
      RETURN PID;
   EXCEPTION
      WHEN OTHERS THEN
         IF GET_ROBOT_TYPE%ISOPEN THEN
            CLOSE GET_ROBOT_TYPE;
         END IF;
         RAISE;
   END ADDROBOTTYPE;

END PKG_ROBOT;
