CREATE OR REPLACE PACKAGE PKG_SHOPPING AS
   FUNCTION ADDSHOPPING (
      PNAME IN SHOPPING.NAME%TYPE
   ) RETURN NUMBER;

   FUNCTION ADDSHOPLEVEL (
      PSHOPPINGID IN SHOPLEVEL.SHOPPINGID%TYPE,
      PLEVELVALUE IN SHOPLEVEL.LEVELVALUE%TYPE
   ) RETURN NUMBER;

END PKG_SHOPPING;
/

CREATE OR REPLACE PACKAGE BODY PKG_SHOPPING AS

   CURSOR GET_SHOP_NAME (
      PNAME IN SHOPPING.NAME%TYPE
   ) IS
   SELECT 1
     FROM SHOPPING
    WHERE NAME = PNAME;

   CURSOR GET_SHOP_LEVEL (
      PSHOPPINGID IN SHOPLEVEL.SHOPPINGID%TYPE,
      PLEVELVALUE IN SHOPLEVEL.LEVELVALUE%TYPE
   ) IS
   SELECT 1
     FROM SHOPLEVEL
    WHERE SHOPPINGID = PSHOPPINGID
      AND LEVELVALUE = PLEVELVALUE;

   CURSOR GET_SHOP (
      PSHOPPINGID IN SHOPPING.SHOPPINGID%TYPE
   ) IS
   SELECT 1
     FROM SHOPPING
    WHERE SHOPPINGID = PSHOPPINGID;

   FUNCTION ADDSHOPPING (
      PNAME IN SHOPPING.NAME%TYPE
   ) RETURN NUMBER IS
      T_SHOP_NAME NUMBER(1);
      PSHOPPINGID SHOPPING.SHOPPINGID%TYPE;
   BEGIN
      IF PNAME IS NULL THEN
         RAISE_APPLICATION_ERROR(
            -20000,
            'All parameters are required.'
         );
      END IF;
      OPEN GET_SHOP_NAME(PNAME);
      FETCH GET_SHOP_NAME INTO T_SHOP_NAME;
      IF GET_SHOP_NAME%FOUND THEN
         CLOSE GET_SHOP_NAME;
         RAISE_APPLICATION_ERROR(
            -20200,
            'Shopping name already exists'
         );
         RETURN 0;
      END IF;

      CLOSE GET_SHOP_NAME;
      LOCK TABLE SHOPPING IN EXCLUSIVE MODE;
      SELECT NVL(
         MAX(SHOPPINGID),
         0
      ) + 1
        INTO PSHOPPINGID
        FROM SHOPPING;

      INSERT INTO SHOPPING (
         SHOPPINGID,
         NAME
      ) VALUES
         ( PSHOPPINGID,
           PNAME );

      COMMIT;
      RETURN PSHOPPINGID;
   EXCEPTION
      WHEN OTHERS THEN
         IF GET_SHOP_NAME%ISOPEN THEN
            CLOSE GET_SHOP_NAME;
         END IF;
         RAISE;
   END ADDSHOPPING;

   FUNCTION ADDSHOPLEVEL (
      PSHOPPINGID IN SHOPLEVEL.SHOPPINGID%TYPE,
      PLEVELVALUE IN SHOPLEVEL.LEVELVALUE%TYPE
   ) RETURN NUMBER IS
      PLEVELID     SHOPLEVEL.LEVELID%TYPE;
      T_SHOP       NUMBER(1);
      T_SHOP_LEVEL NUMBER(1);
   BEGIN
      IF PSHOPPINGID IS NULL
      OR PLEVELVALUE IS NULL THEN
         RAISE_APPLICATION_ERROR(
            -20000,
            'All parameters are required.'
         );
      END IF;

      OPEN GET_SHOP_LEVEL(
         PSHOPPINGID,
         PLEVELVALUE
      );
      FETCH GET_SHOP_LEVEL INTO T_SHOP_LEVEL;
      IF GET_SHOP_LEVEL%FOUND THEN
         CLOSE GET_SHOP_LEVEL;
         RAISE_APPLICATION_ERROR(
            -20201,
            'Level value already exists'
         );
      END IF;

      CLOSE GET_SHOP_LEVEL;
      OPEN GET_SHOP(PSHOPPINGID);
      FETCH GET_SHOP INTO T_SHOP;
      IF GET_SHOP%NOTFOUND THEN
         CLOSE GET_SHOP;
         RAISE_APPLICATION_ERROR(
            -20202,
            'Shopping Id not found'
         );
      END IF;

      CLOSE GET_SHOP;
      LOCK TABLE SHOPPING IN EXCLUSIVE MODE;
      SELECT NVL(
         MAX(LEVELID),
         0
      ) + 1
        INTO PLEVELID
        FROM SHOPLEVEL;

      INSERT INTO SHOPLEVEL (
         LEVELID,
         SHOPPINGID,
         LEVELVALUE
      ) VALUES
         ( PLEVELID,
           PSHOPPINGID,
           PLEVELVALUE );

      COMMIT;
      RETURN PLEVELID;
   EXCEPTION
      WHEN OTHERS THEN
         IF GET_SHOP%ISOPEN THEN
            CLOSE GET_SHOP;
         END IF;
         RAISE;
   END ADDSHOPLEVEL;

END PKG_SHOPPING;
