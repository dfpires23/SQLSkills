CREATE OR REPLACE PACKAGE PKG_CUSTOMER_ORDER AS
   FUNCTION ADDCUSTOMERORDER (
      PCUSTOMERID   IN CUSTOMERORDER.CUSTOMERID%TYPE,
      PDELIVERYTIME IN CUSTOMERORDER.DELIVERYTIME%TYPE
   ) RETURN NUMBER;

   FUNCTION ADDORDERITEM (
      PORDERID    IN ORDERITEM.ORDERID%TYPE,
      PCUSTOMERID IN CUSTOMERORDER.CUSTOMERID%TYPE
   ) RETURN BOOLEAN;

   FUNCTION ADDSUBORDER (
      PORDERID    IN SUBORDER.ORDERID%TYPE,
      PSUBORDERNO IN SUBORDER.SUBORDERNO%TYPE,
      PROBOTID    IN SUBORDER.ROBOTID%TYPE
   ) RETURN NUMBER;

   FUNCTION ADDSUBORDERITEM (
      PORDERID    IN SUBORDERITEM.ORDERID%TYPE,
      PITEMNO     IN SUBORDERITEM.ITEMNO%TYPE,
      PSUBORDERNO IN SUBORDERITEM.SUBORDERNO%TYPE,
      PQUANTITY   IN SUBORDERITEM.QUANTITY%TYPE
   ) RETURN NUMBER;

   FUNCTION UPDATEPRODUCTSTOCK (
      PPRODUCTID IN PRODUCT.PRODUCTID%TYPE,
      PQUANTITY  IN CARTITEM.QUANTITY%TYPE
   ) RETURN BOOLEAN;

END PKG_CUSTOMER_ORDER;
/

CREATE OR REPLACE PACKAGE BODY PKG_CUSTOMER_ORDER AS

   CURSOR GET_CUSTOMER (
      PCUSTOMERID IN CUSTOMERORDER.CUSTOMERID%TYPE
   ) IS
   SELECT 1
     FROM CUSTOMER
    WHERE CUSTOMERID = PCUSTOMERID;

   CURSOR GET_CART_ID (
      PCUSTOMERID IN CUSTOMERORDER.CUSTOMERID%TYPE
   ) IS
   SELECT CARTID
     FROM SHOPPINGCART
    WHERE CUSTOMERID = PCUSTOMERID;

   CURSOR GET_CART_ITEMS (
      PCUSTOMERID IN CUSTOMERORDER.CUSTOMERID%TYPE
   ) IS
   SELECT CARTITEM.PRODUCTID,
          CARTITEM.QUANTITY,
          PRODUCT.PRICEEUR
     FROM SHOPPINGCART,
          CARTITEM,
          PRODUCT
    WHERE SHOPPINGCART.CARTID = CARTITEM.CARTID
      AND PRODUCT.PRODUCTID = CARTITEM.PRODUCTID
      AND SHOPPINGCART.CUSTOMERID = PCUSTOMERID;

   CURSOR GET_ROBOT_STATUS (
      PROBOTID IN ROBOT.ROBOTID%TYPE
   ) IS
   SELECT ROBOT.STATUS
     FROM ROBOT
    WHERE ROBOT.ROBOTID = PROBOTID;

   CURSOR GET_PRODUCT_STOCK (
      PPRODUCTID IN PRODUCT.PRODUCTID%TYPE
   ) IS
   SELECT STOCKUNITS
     FROM PRODUCT
    WHERE PRODUCTID = PPRODUCTID
   FOR UPDATE;

   FUNCTION UPDATEPRODUCTSTOCK (
      PPRODUCTID IN PRODUCT.PRODUCTID%TYPE,
      PQUANTITY  IN CARTITEM.QUANTITY%TYPE
   ) RETURN BOOLEAN IS
      T_STOCK PRODUCT.STOCKUNITS%TYPE;
   BEGIN
      OPEN GET_PRODUCT_STOCK(PPRODUCTID);
      FETCH GET_PRODUCT_STOCK INTO T_STOCK;
      IF GET_PRODUCT_STOCK%NOTFOUND THEN
         CLOSE GET_PRODUCT_STOCK;
         RETURN FALSE;
      END IF;
      CLOSE GET_PRODUCT_STOCK;
      IF T_STOCK < PQUANTITY THEN
         RETURN FALSE;
      END IF;
      IF PQUANTITY IS NULL
      OR PQUANTITY <= 0
      OR PQUANTITY <> TRUNC(PQUANTITY) THEN
         RETURN FALSE;
      END IF;

      UPDATE PRODUCT
         SET
         STOCKUNITS = STOCKUNITS - PQUANTITY
       WHERE PRODUCTID = PPRODUCTID;

      RETURN TRUE;
   EXCEPTION
      WHEN OTHERS THEN
         IF GET_PRODUCT_STOCK%ISOPEN THEN
            CLOSE GET_PRODUCT_STOCK;
         END IF;
   END UPDATEPRODUCTSTOCK;

   FUNCTION ADDCUSTOMERORDER (
      PCUSTOMERID   IN CUSTOMERORDER.CUSTOMERID%TYPE,
      PDELIVERYTIME IN CUSTOMERORDER.DELIVERYTIME%TYPE
   ) RETURN NUMBER IS

      PORDERID      CUSTOMERORDER.ORDERID%TYPE;
      PCODE         CUSTOMERORDER.CODE%TYPE;
      VDELIVERYTIME CUSTOMERORDER.DELIVERYTIME%TYPE;
      T_CART_ID     SHOPPINGCART.CARTID%TYPE;
      T_CUSTOMER    NUMBER(1);
      L_RESULT      BOOLEAN;
   BEGIN
      IF PCUSTOMERID IS NULL
      OR PDELIVERYTIME IS NULL THEN
         RAISE_APPLICATION_ERROR(
            -20000,
            'All parameters are required.'
         );
      END IF;
	
		-- alteração para usar diferentes time zones e manter horas corretas
      VDELIVERYTIME := PDELIVERYTIME AT TIME ZONE 'UTC';
      IF VDELIVERYTIME <= SYSTIMESTAMP THEN
         RAISE_APPLICATION_ERROR(
            -20001,
            'Delivey date must be in the future!'
         );
      END IF;
      OPEN GET_CUSTOMER(PCUSTOMERID);
      FETCH GET_CUSTOMER INTO T_CUSTOMER;
      IF GET_CUSTOMER%NOTFOUND THEN
         CLOSE GET_CUSTOMER;
         RAISE_APPLICATION_ERROR(
            -20002,
            'Customer not found!'
         );
      END IF;

      CLOSE GET_CUSTOMER;
      BEGIN
         SAVEPOINT SP_ADD_CUSTOMER_ORDER;
         LOCK TABLE CUSTOMERORDER IN EXCLUSIVE MODE;
         SELECT NVL(
            MAX(ORDERID),
            0
         ) + 1
           INTO PORDERID
           FROM CUSTOMERORDER;

         PCODE := 'Order_'
                  || LPAD(
            PORDERID,
            6,
            '0'
         );
         INSERT INTO CUSTOMERORDER (
            ORDERID,
            CODE,
            CUSTOMERID,
            DELIVERYTIME
         ) VALUES
            ( PORDERID,
              PCODE,
              PCUSTOMERID,
              PDELIVERYTIME );

         L_RESULT := ADDORDERITEM(
            PORDERID,
            PCUSTOMERID
         );
         IF NOT L_RESULT THEN
            ROLLBACK TO SP_ADD_CUSTOMER_ORDER;
            RAISE_APPLICATION_ERROR(
               -20003,
               'Error creating customer order item(s)'
            );
         END IF;

         OPEN GET_CART_ID(PCUSTOMERID);
         FETCH GET_CART_ID INTO T_CART_ID;
         IF GET_CART_ID%NOTFOUND THEN
            CLOSE GET_CART_ID;
            ROLLBACK TO SP_ADD_CUSTOMER_ORDER;
            RAISE_APPLICATION_ERROR(
               -20004,
               'Customer cart not found!'
            );
         END IF;

         DELETE FROM CARTITEM
          WHERE CARTID = T_CART_ID;

         CLOSE GET_CART_ID;
         COMMIT;
         RETURN PORDERID;
      EXCEPTION
         WHEN OTHERS THEN
            IF GET_CUSTOMER%ISOPEN THEN
               CLOSE GET_CUSTOMER;
            END IF;
            IF GET_CART_ID%ISOPEN THEN
               CLOSE GET_CART_ID;
            END IF;
            ROLLBACK TO SP_ADD_CUSTOMER_ORDER;
            RAISE;
      END;

   END ADDCUSTOMERORDER;

   FUNCTION ADDORDERITEM (
      PORDERID    IN ORDERITEM.ORDERID%TYPE,
      PCUSTOMERID IN CUSTOMERORDER.CUSTOMERID%TYPE
   ) RETURN BOOLEAN IS

      PITEMNO      ORDERITEM.ITEMNO%TYPE;
      T_PRODUCT    PRODUCT.PRODUCTID%TYPE;
      T_QUANTITY   CARTITEM.QUANTITY%TYPE;
      T_UNIT_PRICE ORDERITEM.UNITPRICEEUR%TYPE;
      L_RESULT     BOOLEAN;
   BEGIN
      PITEMNO := 1;
      OPEN GET_CART_ITEMS(PCUSTOMERID);
      LOOP
         FETCH GET_CART_ITEMS INTO
            T_PRODUCT,
            T_QUANTITY,
            T_UNIT_PRICE;
         EXIT WHEN GET_CART_ITEMS%NOTFOUND;
         L_RESULT := UPDATEPRODUCTSTOCK(
            T_PRODUCT,
            T_QUANTITY
         );
         IF NOT L_RESULT THEN
            RAISE_APPLICATION_ERROR(
               -20005,
               'Insufficient stock for product: ' || T_PRODUCT
            );
         END IF;
         INSERT INTO ORDERITEM (
            ORDERID,
            ITEMNO,
            PRODUCTID,
            QUANTITY,
            UNITPRICEEUR
         ) VALUES
            ( PORDERID,
              PITEMNO,
              T_PRODUCT,
              T_QUANTITY,
              T_UNIT_PRICE );

         PITEMNO := PITEMNO + 1;
      END LOOP;

      CLOSE GET_CART_ITEMS;
      IF PITEMNO = 1 THEN
         RAISE_APPLICATION_ERROR(
            -20006,
            'Item(s) not found!'
         );
      END IF;
      RETURN TRUE;
   EXCEPTION
      WHEN OTHERS THEN
         IF GET_CART_ITEMS%ISOPEN THEN
            CLOSE GET_CART_ITEMS;
         END IF;
         RAISE;
   END ADDORDERITEM;

   FUNCTION ADDSUBORDER (
      PORDERID    IN SUBORDER.ORDERID%TYPE,
      PSUBORDERNO IN SUBORDER.SUBORDERNO%TYPE,
      PROBOTID    IN SUBORDER.ROBOTID%TYPE
   ) RETURN NUMBER IS
      T_ROBOT_STATUS ROBOT.STATUS%TYPE;
   BEGIN
      IF PORDERID IS NULL
      OR PSUBORDERNO IS NULL
      OR PROBOTID IS NULL THEN
         RAISE_APPLICATION_ERROR(
            -20000,
            'All parameters are required.'
         );
      END IF;

      OPEN GET_ROBOT_STATUS(PROBOTID);
      FETCH GET_ROBOT_STATUS INTO T_ROBOT_STATUS;
      IF GET_ROBOT_STATUS%NOTFOUND THEN
         CLOSE GET_ROBOT_STATUS;
         RAISE_APPLICATION_ERROR(
            -20007,
            'Robot not found!'
         );
      ELSIF T_ROBOT_STATUS <> 'READY' THEN
         CLOSE GET_ROBOT_STATUS;
         RAISE_APPLICATION_ERROR(
            -20008,
            'Robot not ready!'
         );
      END IF;

      CLOSE GET_ROBOT_STATUS;
      BEGIN
         SAVEPOINT SP_ADD_CUSTOMER_SUBORDER;
         INSERT INTO SUBORDER (
            ORDERID,
            SUBORDERNO,
            ROBOTID
         ) VALUES
            ( PORDERID,
              PSUBORDERNO,
              PROBOTID );

         UPDATE ROBOT
            SET
            STATUS = 'BUSY'
          WHERE ROBOTID = PROBOTID;

         COMMIT;
         RETURN 1;
      EXCEPTION
         WHEN OTHERS THEN
            IF GET_ROBOT_STATUS%ISOPEN THEN
               CLOSE GET_ROBOT_STATUS;
            END IF;
            ROLLBACK TO SP_ADD_CUSTOMER_SUBORDER;
            RAISE;
      END;

   END ADDSUBORDER;

   FUNCTION ADDSUBORDERITEM (
      PORDERID    IN SUBORDERITEM.ORDERID%TYPE,
      PITEMNO     IN SUBORDERITEM.ITEMNO%TYPE,
      PSUBORDERNO IN SUBORDERITEM.SUBORDERNO%TYPE,
      PQUANTITY   IN SUBORDERITEM.QUANTITY%TYPE
   ) RETURN NUMBER IS
      VCOUNT NUMBER;
   BEGIN
      IF PORDERID IS NULL
      OR PITEMNO IS NULL
      OR PSUBORDERNO IS NULL
      OR PQUANTITY IS NULL
      OR PQUANTITY <= 0
      OR PQUANTITY <> TRUNC(PQUANTITY) THEN
         RAISE_APPLICATION_ERROR(
            -20000,
            'All parameters are required.'
         );
      END IF;

      INSERT INTO SUBORDERITEM (
         ORDERID,
         ITEMNO,
         SUBORDERNO,
         QUANTITY
      ) VALUES
         ( PORDERID,
           PITEMNO,
           PSUBORDERNO,
           PQUANTITY );

      RETURN 1;
   EXCEPTION
      WHEN OTHERS THEN
         RAISE;
   END ADDSUBORDERITEM;

END PKG_CUSTOMER_ORDER;
