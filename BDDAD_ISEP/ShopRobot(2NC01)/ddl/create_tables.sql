CREATE TABLE SHOPPING (
   SHOPPINGID NUMBER(10) NOT NULL,
   NAME       VARCHAR2(200) NOT NULL,
   CONSTRAINT PKSHOPPING PRIMARY KEY ( SHOPPINGID ),
   CONSTRAINT UQ_SHOPPINGNAME UNIQUE ( NAME )
);

CREATE TABLE SHOPLEVEL (
   LEVELID    NUMBER(10) NOT NULL,
   SHOPPINGID NUMBER(10) NOT NULL,
   LEVELVALUE NUMBER(8,3) NOT NULL,
   CONSTRAINT PKSHOPLEVEL PRIMARY KEY ( LEVELID ),
   CONSTRAINT UQSHOPLEVEL1 UNIQUE ( SHOPPINGID,
                                    LEVELVALUE )
);

CREATE TABLE AREA (
   AREAID       NUMBER(10) NOT NULL,
   SHOPPINGID   NUMBER(10) NOT NULL,
   MAPID        VARCHAR2(100) NOT NULL,
   NAME         VARCHAR2(200),
   GEOMETRYTYPE VARCHAR2(20) NOT NULL,
   LONGITUDE    NUMBER(12,9) NOT NULL,
   LATITUDE     NUMBER(12,9) NOT NULL,
   CONSTRAINT PKAREA PRIMARY KEY ( AREAID ),
   CONSTRAINT UQAREA1 UNIQUE ( SHOPPINGID,
                               MAPID ),
   CONSTRAINT CKAREA3 CHECK ( LATITUDE BETWEEN - 90 AND 90 ),
   CONSTRAINT CKAREA2 CHECK ( LONGITUDE BETWEEN - 180 AND 180 ),
   CONSTRAINT CKAREA1 CHECK ( GEOMETRYTYPE IN ( 'Polygon',
                                                'MultiPolygon' ) )
);

CREATE TABLE AREALEVEL (
   AREAID  NUMBER(10) NOT NULL,
   LEVELID NUMBER(10) NOT NULL,
   CONSTRAINT PKAREALEVEL PRIMARY KEY ( AREAID,
                                        LEVELID )
);

CREATE TABLE AREACLASSIFICATION (
   AREAID             NUMBER(10) NOT NULL,
   CLASSIFICATIONTYPE VARCHAR2(30) NOT NULL,
   CATEGORY           VARCHAR2(100) NOT NULL,
   CONSTRAINT PKAREACLASSIFICATION PRIMARY KEY ( AREAID,
                                                 CLASSIFICATIONTYPE ),
   CONSTRAINT CKAREACLASSIFICATION1
      CHECK ( CLASSIFICATIONTYPE IN ( 'indoor',
                                      'shop',
                                      'amenity',
                                      'craft',
                                      'highway' ) )
);

CREATE TABLE STORE (
   STOREID NUMBER(10) NOT NULL,
   AREAID  NUMBER(10) NOT NULL,
   CONSTRAINT PKSTORE PRIMARY KEY ( STOREID ),
   CONSTRAINT UQSTORE1 UNIQUE ( AREAID )
);

CREATE TABLE AREAPOLYGON (
   AREAID     NUMBER(10) NOT NULL,
   POLYGONNO  NUMBER(10) NOT NULL,
   BOUNDARYNO NUMBER(10) NOT NULL,
   POINTORDER NUMBER(10) NOT NULL,
   LONGITUDE  NUMBER(12,9) NOT NULL,
   LATITUDE   NUMBER(12,9) NOT NULL,
   CONSTRAINT PKAREAPOLYGON
      PRIMARY KEY ( AREAID,
                    POLYGONNO,
                    BOUNDARYNO,
                    POINTORDER ),
   CONSTRAINT CKAREAPOLYGON5 CHECK ( LATITUDE BETWEEN - 90 AND 90 ),
   CONSTRAINT CKAREAPOLYGON4 CHECK ( LONGITUDE BETWEEN - 180 AND 180 ),
   CONSTRAINT CKAREAPOLYGON3 CHECK ( POINTORDER > 0 ),
   CONSTRAINT CKAREAPOLYGON2 CHECK ( BOUNDARYNO > 0 ),
   CONSTRAINT CKAREAPOLYGON1 CHECK ( POLYGONNO > 0 )
);

CREATE TABLE PRODUCT (
   PRODUCTID    NUMBER(10) NOT NULL,
   CODE         VARCHAR2(40) NOT NULL,
   STOREID      NUMBER(10) NOT NULL,
   NAME         VARCHAR2(200) NOT NULL,
   WEIGHTKG     NUMBER(12,4) NOT NULL,
   VOLUMEL      NUMBER(12,4) NOT NULL,
   NEEDSCOOLING NUMBER(1) NOT NULL,
   PRICEEUR     NUMBER(12,2) NOT NULL,
   STOCKUNITS   NUMBER(19) NOT NULL,
   CONSTRAINT PKPRODUCT PRIMARY KEY ( PRODUCTID ),
   CONSTRAINT UQPRODUCT1 UNIQUE ( CODE ),
   CONSTRAINT UQPRODUCTSTORENAME UNIQUE ( STOREID,
                                          NAME ),
   CONSTRAINT CKPRODUCTSTOCK CHECK ( STOCKUNITS >= 0 ),
   CONSTRAINT CKPRODUCTCOOLING CHECK ( NEEDSCOOLING IN ( 0,
                                                         1 ) ),
   CONSTRAINT CKPRODUCTVOLUME CHECK ( VOLUMEL > 0 ),
   CONSTRAINT CKPRODUCTWEIGHT CHECK ( WEIGHTKG > 0 ),
   CONSTRAINT CKPRODUCTNAME
      CHECK ( TRIM(NAME) IS NOT NULL
         AND LENGTH(NAME) = LENGTH(TRIM(NAME)) ),
   CONSTRAINT CKPRODUCTPRICE CHECK ( PRICEEUR >= 0 )
);

CREATE TABLE CUSTOMER (
   CUSTOMERID NUMBER(10) NOT NULL,
   EMAIL      VARCHAR2(254) NOT NULL,
   FIRSTNAME  VARCHAR2(100) NOT NULL,
   LASTNAME   VARCHAR2(100) NOT NULL,
   CONSTRAINT PKCUSTOMER PRIMARY KEY ( CUSTOMERID ),
   CONSTRAINT UQCUSTOMEREMAIL UNIQUE ( EMAIL )
);

CREATE TABLE CUSTOMERORDER (
   ORDERID      NUMBER(10) NOT NULL,
   CODE         VARCHAR2(40) NOT NULL,
   CUSTOMERID   NUMBER(10) NOT NULL,
   DELIVERYTIME TIMESTAMP(0) WITH TIME ZONE NOT NULL,
   CONSTRAINT PKCUSTOMERORDER PRIMARY KEY ( ORDERID ),
   CONSTRAINT UQCUSTOMERORDER1 UNIQUE ( CODE )
);

CREATE TABLE ORDERITEM (
   ORDERID      NUMBER(10) NOT NULL,
   ITEMNO       NUMBER(10) NOT NULL,
   PRODUCTID    NUMBER(10) NOT NULL,
   QUANTITY     NUMBER(19) NOT NULL,
   UNITPRICEEUR NUMBER(10,2) NOT NULL,
   CONSTRAINT PKORDERITEM PRIMARY KEY ( ORDERID,
                                        ITEMNO ),
   CONSTRAINT CKORDERITEM1 CHECK ( ITEMNO >= 1 ),
   CONSTRAINT CKORDERITEMPRICE CHECK ( UNITPRICEEUR >= 0 ),
   CONSTRAINT CKORDERITEMQTY CHECK ( QUANTITY > 0 )
);

CREATE TABLE SHOPPINGCART (
   CARTID     NUMBER(10) NOT NULL,
   CUSTOMERID NUMBER(10) NOT NULL,
   CONSTRAINT PKSHOPPINGCART PRIMARY KEY ( CARTID ),
   CONSTRAINT UQSHOPPINGCARTCUSTOMER UNIQUE ( CUSTOMERID )
);

CREATE TABLE CARTITEM (
   CARTID    NUMBER(10) NOT NULL,
   PRODUCTID NUMBER(10) NOT NULL,
   QUANTITY  NUMBER(19) NOT NULL,
   CONSTRAINT PKCARTITEM PRIMARY KEY ( CARTID,
                                       PRODUCTID ),
   CONSTRAINT CKCARTITEM1 CHECK ( QUANTITY > 0 )
);

CREATE TABLE ROBOT (
   SHOPPINGID NUMBER(10) NOT NULL,
   ROBOTID    NUMBER(10) NOT NULL,
   ROBOTCODE  VARCHAR2(40) NOT NULL,
   NAME       VARCHAR2(100) NOT NULL,
   TYPEID     NUMBER(10) NOT NULL,
   BATTERYPCT NUMBER(5,2) NOT NULL,
   STATUS     VARCHAR2(30) NOT NULL,
   CONSTRAINT PKROBOT PRIMARY KEY ( ROBOTID ),
   CONSTRAINT UQROBOT1 UNIQUE ( ROBOTCODE ),
   CONSTRAINT CKROBOT5
      CHECK ( STATUS IN ( 'READY',
                          'BUSY',
                          'CHARGING',
                          'MAINTENANCE' ) ),
   CONSTRAINT CKROBOT4 CHECK ( BATTERYPCT BETWEEN 0 AND 100 )
);

CREATE TABLE SUBORDER (
   ORDERID    NUMBER(10) NOT NULL,
   SUBORDERNO NUMBER(10) NOT NULL,
   ROBOTID    NUMBER(10) NOT NULL,
   CONSTRAINT PKSUBORDER PRIMARY KEY ( ORDERID,
                                       SUBORDERNO ),
   CONSTRAINT UQSUBORDER1 UNIQUE ( ROBOTID ),
   CONSTRAINT CKSUBORDER1 CHECK ( SUBORDERNO >= 1 )
);

CREATE TABLE SUBORDERITEM (
   ORDERID    NUMBER(10) NOT NULL,
   ITEMNO     NUMBER(10) NOT NULL,
   SUBORDERNO NUMBER(10) NOT NULL,
   QUANTITY   NUMBER(19) NOT NULL,
   CONSTRAINT PKSUBORDERITEM PRIMARY KEY ( ORDERID,
                                           ITEMNO,
                                           SUBORDERNO ),
   CONSTRAINT CKSUBORDERITEMQTY CHECK ( QUANTITY > 0 )
);

CREATE TABLE ROBOTTYPE (
   ID          NUMBER(10) NOT NULL,
   MAXWEIGHTKG NUMBER(12,4) NOT NULL,
   MAXVOLUMEL  NUMBER(12,4) NOT NULL,
   HASCOOLING  NUMBER(1) NOT NULL,
   PRIMARY KEY ( ID ),
   CONSTRAINT UQ_ROBOTTYPE UNIQUE ( MAXWEIGHTKG,
                                    MAXVOLUMEL,
                                    HASCOOLING ),
   CONSTRAINT CKROBOTWEIGHT CHECK ( MAXWEIGHTKG > 0 ),
   CONSTRAINT CKROBOTCOOLING CHECK ( HASCOOLING IN ( 0,
                                                     1 ) ),
   CONSTRAINT CKROBOTVOLUME CHECK ( MAXVOLUMEL > 0 )
);

